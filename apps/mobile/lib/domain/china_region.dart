final _bounds = (
  west: mainlandChinaOutline.map((p) => p.$1).reduce((a, b) => a < b ? a : b),
  east: mainlandChinaOutline.map((p) => p.$1).reduce((a, b) => a > b ? a : b),
  south: mainlandChinaOutline.map((p) => p.$2).reduce((a, b) => a < b ? a : b),
  north: mainlandChinaOutline.map((p) => p.$2).reduce((a, b) => a > b ? a : b),
);

bool _inRing(double lon, double lat, List<(double, double)> ring) {
  var inside = false;
  for (var i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    final (xi, yi) = ring[i];
    final (xj, yj) = ring[j];
    if ((yi > lat) != (yj > lat) &&
        lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/// True for a WGS-84 position in mainland China (Hong Kong, Macau and Taiwan
/// return false).
bool isMainlandChinaCoordinate(double latitude, double longitude) {
  if (!latitude.isFinite || !longitude.isFinite) return false;
  if (longitude < _bounds.west ||
      longitude > _bounds.east ||
      latitude < _bounds.south ||
      latitude > _bounds.north) {
    return false;
  }
  if (!_inRing(longitude, latitude, mainlandChinaOutline)) return false;
  return !mainlandChinaExclusions.values.any(
    (ring) => _inRing(longitude, latitude, ring),
  );
}

bool isMainlandChina(GeoPoint? point) =>
    point != null &&
    point.isValid &&
    isMainlandChinaCoordinate(point.latitude, point.longitude);

